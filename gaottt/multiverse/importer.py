"""Multiverse importer — pure business logic for adopting a standalone data_dir.

Transforms an existing standalone ``data_dir`` (the single-user ``gaottt.db`` +
FAISS cluster layout) into one universe under ``<multiverse_root>/universes/<uid>/``
with a managed manifest, a registry row, and a freshly issued API key.

Design constraints (plan §2.4 / §2.5):

* **Pure planning, side-effecting execution.** ``build_import_plan`` is a pure
  function — it produces an :class:`ImportPlan` that ``--dry-run`` can print
  without touching the filesystem. ``execute_import`` is the only mutating
  entry point and owns the transaction scope.
* **Transaction scope = max-3 retry unit.** ``allocate_port → mkdir → copy/move
  → integrity_check → manifest → registry.create_universe`` is wrapped in a
  single retry unit. IntegrityError (the partial UNIQUE INDEX on
  ``universes.port``) triggers cleanup + retry; any other exception triggers
  cleanup + re-raise. This guarantees no stray ``universes/<uid>/`` dir is left
  unregistered (which would make supervisor ``reconcile`` WARN).
* **Source identity, not past-vector identity.** ``resolve_embedder_identity``
  records ``config.embedding_dim`` as a *runtime expectation* — the real proof
  happens at target ``engine.startup`` (FAISS load + manifest check). The
  importer cannot falsify semantic drift; it only refuses to import when the
  configured embedder service is unreachable or reports a different identity.
* **Allowlist copy.** Only ``COPY_FILENAMES`` are copied; every other file
  (backups, manifests, owner locks, tokens, registry dbs) is skipped with a
  reason so the target dir is operationally clean.
"""
from __future__ import annotations

import json
import logging
import shutil
import sqlite3
import time
import uuid
from dataclasses import dataclass
from pathlib import Path
from typing import TYPE_CHECKING

import aiosqlite

from gaottt.config import GaOTTTConfig
from gaottt.store.manifest import UniverseManifest, load_manifest, write_manifest

if TYPE_CHECKING:
    from gaottt.multiverse.registry import MultiverseRegistry

logger = logging.getLogger(__name__)

# ---------------------------------------------------------------------------
# Constants — copy allowlist + classification heuristics
# ---------------------------------------------------------------------------

# The 7 canonical copy targets (plan §2.3 step 6). ``-wal`` / ``-shm`` absence
# is normal (clean checkpoint completed); presence is fine too.
COPY_FILENAMES: tuple[str, ...] = (
    "gaottt.db",
    "gaottt.db-shm",
    "gaottt.db-wal",
    "gaottt.faiss",
    "gaottt.faiss.ids",
    "gaottt.virtual.faiss",
    "gaottt.virtual.faiss.ids",
)

# Substring classifiers for the ``skipped`` report. Each (substring, reason)
# pair is checked in order; the first match wins. A file that matches none and
# is not in COPY_FILENAMES gets the generic ``unrecognized`` reason.
_SKIP_CLASSIFIERS: tuple[tuple[str, str], ...] = (
    (".bak", "backup file"),
    (".before-", "pre-migration backup"),
    (".post-", "post-migration snapshot"),
    (".broken-", "broken / quarantined"),
    (".tmp", "temporary scratch file"),
    ("manifest.json", "regenerated at target (managed=True)"),
    ("owner.lock", "lease bookkeeping, regenerated by target backend"),
    ("owner.lock.guard", "lease guard, regenerated by target backend"),
    ("backend.token", "auth token, regenerated by supervisor spawn"),
    ("registry.db", "multiverse registry db (not a universe data file)"),
    ("memory.db", "legacy memory db"),
    ("?mode=ro", "legacy read-only shim"),
)

# Post-copy retry budget. The partial UNIQUE INDEX ``idx_universes_port_live``
# is the DB-level backstop against a concurrent supervisor allocating the same
# port; we retry the whole allocate→copy→manifest→create unit on
# IntegrityError so the importer self-heals instead of leaving a stray dir.
_MAX_ATTEMPTS = 3


# ---------------------------------------------------------------------------
# Dataclasses — shapes pinned by tests/unit/test_importer.py
# ---------------------------------------------------------------------------


@dataclass
class FilePlan:
    """Result of scanning ``source`` for copy targets.

    ``copy_files`` is the subset of :data:`COPY_FILENAMES` actually present.
    ``skipped`` lists every other file with a human-readable reason (for the
    dry-run report and the ``--move`` residue WARNING). ``total_bytes`` is the
    sum of ``st_size`` across ``copy_files`` — the budget for the disk-capacity
    gate (sparse files report their nominal size, which is what we want: the
    target filesystem must hold the post-copy bytes).
    """

    copy_files: list[str]
    skipped: list[tuple[str, str]]
    total_bytes: int


@dataclass
class ImportPlan:
    """A dry-run-renderable, side-effect-free import plan.

    ``port`` is ``None`` at build time and resolved inside :func:`execute_import`
    via ``registry.allocate_port`` — keeping planning pure lets ``--dry-run``
    run without a registry. ``embedding_dim`` is the *runtime expectation*
    (config-derived); it is recorded in the target manifest but is NOT a proof
    of source FAISS dimensionality. The hard check lives in
    :func:`gaottt.core.engine.GaOTTTEngine.startup` (manifest gate + FAISS load).
    """

    universe_id: str
    source: Path
    target: Path
    owner_label: str
    port: int | None
    embedder_id: str
    embedder_version: str
    embedding_dim: int
    file_plan: FilePlan
    mode: str  # "copy" | "move"


# ---------------------------------------------------------------------------
# Exceptions — distinct types so the CLI can map them to specific exit codes
# without string-matching RuntimeError messages.
# ---------------------------------------------------------------------------


class IntegrityCheckFailed(RuntimeError):
    """Post-copy ``PRAGMA integrity_check`` returned non-``ok`` (or the target
    db is missing / unopenable / schemaless).

    Raised by :func:`_verify_target_db`. The CLI maps this to exit 8.
    """


class UniverseAlreadyExistsError(RuntimeError):
    """``plan.universe_id`` is already present in the registry.

    Raised by :func:`execute_import` before the retry loop so the
    ``create_universe`` PRIMARY KEY IntegrityError is not misclassified as a
    port race. The CLI maps this to exit 2 (argument error — same as
    :func:`validate_universe_id` rejection).
    """


